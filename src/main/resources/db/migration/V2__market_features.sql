alter table account add column liquidity_provider boolean not null default false;

create table price_history (
  symbol varchar(12) not null references instrument(symbol),
  trade_date date not null,
  open_mills bigint not null, high_mills bigint not null, low_mills bigint not null, close_mills bigint not null,
  volume bigint not null,
  primary key (symbol, trade_date)
);
create table financials (
  symbol varchar(12) primary key references instrument(symbol),
  period varchar(8) not null,
  shares_outstanding bigint not null,
  assets_mills bigint not null, liabilities_mills bigint not null, profit_mills bigint not null,
  dividend_per_share_mills bigint not null,
  up_days_year int not null
);
create table news_item (
  id bigint generated by default as identity primary key,
  kind varchar(12) not null,
  symbol varchar(12),
  published_on date not null,
  title varchar(200) not null,
  body varchar(600) not null
);
create table favorite (
  owner varchar(40) not null, symbol varchar(12) not null references instrument(symbol),
  primary key (owner, symbol)
);
create table price_alert (
  id bigint generated by default as identity primary key,
  owner varchar(40) not null,
  symbol varchar(12) not null references instrument(symbol),
  direction varchar(5) not null,
  price_mills bigint not null,
  status varchar(10) not null,
  created_at timestamp not null,
  triggered_at timestamp,
  triggered_price_mills bigint
);
create index idx_alert_active on price_alert (symbol, status);
create table cash_transfer (
  id bigint generated by default as identity primary key,
  account_id bigint not null references account(id),
  client_ref varchar(40) not null,
  direction varchar(8) not null,
  amount_mills bigint not null,
  bank varchar(40) not null,
  rail varchar(12) not null,
  status varchar(12) not null,
  created_at timestamp not null,
  constraint uq_transfer_ref unique (account_id, client_ref)
);
create table account_application (
  id bigint generated by default as identity primary key,
  full_name varchar(80) not null,
  email varchar(120) not null,
  applicant_type varchar(16) not null,
  note varchar(300),
  status varchar(10) not null,
  created_at timestamp not null
);
