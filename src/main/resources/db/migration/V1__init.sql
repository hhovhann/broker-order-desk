create table instrument (
  symbol varchar(12) primary key,
  name varchar(80) not null,
  reference_price_mills bigint not null,
  last_price_mills bigint not null
);
create table account (
  id bigint generated by default as identity primary key,
  owner varchar(40) not null unique,
  cash_mills bigint not null,
  margin_limit_mills bigint not null,
  reserved_mills bigint not null default 0,
  version bigint not null default 0
);
create table holding (
  id bigint generated by default as identity primary key,
  account_id bigint not null references account(id),
  symbol varchar(12) not null references instrument(symbol),
  quantity bigint not null,
  reserved_qty bigint not null default 0,
  constraint uq_holding unique (account_id, symbol),
  constraint ck_holding check (quantity >= 0 and reserved_qty >= 0 and reserved_qty <= quantity)
);
create table broker_order (
  id bigint generated by default as identity primary key,
  account_id bigint not null references account(id),
  client_order_id varchar(40) not null,
  symbol varchar(12) not null references instrument(symbol),
  side varchar(4) not null,
  quantity bigint not null,
  limit_price_mills bigint not null,
  filled_qty bigint not null default 0,
  filled_notional_mills bigint not null default 0,
  reserved_mills bigint not null default 0,
  status varchar(20) not null,
  reject_reason varchar(40),
  created_at timestamp not null,
  constraint uq_client_order unique (account_id, client_order_id)
);
create index idx_order_open on broker_order (symbol, status);
create table trade (
  id bigint generated by default as identity primary key,
  symbol varchar(12) not null,
  price_mills bigint not null,
  quantity bigint not null,
  buy_order_id bigint not null,
  sell_order_id bigint not null,
  buy_account_id bigint not null,
  sell_account_id bigint not null,
  executed_at timestamp not null
);
create table audit_event (
  id bigint generated by default as identity primary key,
  at timestamp not null,
  actor varchar(40) not null,
  action varchar(40) not null,
  detail varchar(300) not null,
  correlation_id varchar(64)
);
